import { Router } from 'express';
import jwt from 'jsonwebtoken';
import bcrypt from 'bcryptjs';
import { query } from '../db.js';

const router = Router();
const JWT_SECRET = process.env.JWT_SECRET || 'cshub-railway-secret-key-change-in-production';

/**
 * Middleware to authenticate JWT token
 */
export function authenticateToken(req, res, next) {
  const authHeader = req.headers['authorization'];
  const token = authHeader && authHeader.split(' ')[1];

  if (!token) {
    return res.status(401).json({ error: 'Access token required' });
  }

  jwt.verify(token, JWT_SECRET, (err, decoded) => {
    if (err) return res.status(403).json({ error: 'Invalid or expired token' });
    req.user = decoded;
    next();
  });
}

/**
 * Middleware to require admin privileges
 */
export function requireAdmin(req, res, next) {
  authenticateToken(req, res, () => {
    if (req.user && (req.user.role === 'admin' || req.user.role === 'super_admin')) {
      next();
    } else {
      res.status(403).json({ error: 'Admin privileges required' });
    }
  });
}

/**
 * Verify 6-digit Telegram login code (generated by Telegram bot)
 * POST /api/auth/telegram-verify
 * Body: { code: '123456' }
 */
router.post('/telegram-verify', async (req, res) => {
  const { code } = req.body;
  if (!code) {
    return res.status(400).json({ error: 'Verification code is required' });
  }

  try {
    const codeRes = await query(
      `SELECT * FROM telegram_auth_codes 
       WHERE code = $1 AND used = FALSE AND expires_at > NOW()`,
      [code.trim()]
    );

    if (codeRes.rows.length === 0) {
      return res.status(400).json({ error: 'Invalid or expired verification code' });
    }

    const authRecord = codeRes.rows[0];

    // Mark code as used
    await query(`UPDATE telegram_auth_codes SET used = TRUE WHERE code = $1`, [code.trim()]);

    // Fetch user profile
    const userRes = await query(`SELECT * FROM users WHERE id = $1`, [authRecord.user_id]);
    if (userRes.rows.length === 0) {
      return res.status(404).json({ error: 'User profile not found' });
    }

    const user = userRes.rows[0];
    delete user.password_hash;

    const token = jwt.sign(
      { id: user.id, telegram_id: user.telegram_id, role: user.role, email: user.email },
      JWT_SECRET,
      { expiresIn: '30d' }
    );

    res.json({
      token,
      user,
      message: 'Successfully authenticated via Telegram',
    });
  } catch (err) {
    console.error('Telegram verify error:', err);
    res.status(500).json({ error: 'Authentication failed' });
  }
});

/**
 * Admin Login via Email and Password
 * POST /api/auth/admin-login
 */
router.post('/admin-login', async (req, res) => {
  const { email, password } = req.body;
  if (!email || !password) {
    return res.status(400).json({ error: 'Email and password are required' });
  }

  try {
    const userRes = await query(`SELECT * FROM users WHERE email = $1`, [email.toLowerCase().trim()]);
    if (userRes.rows.length === 0) {
      return res.status(401).json({ error: 'Invalid credentials' });
    }

    const user = userRes.rows[0];
    if (user.role !== 'admin' && user.role !== 'super_admin' && user.role !== 'moderator') {
      return res.status(403).json({ error: 'Unauthorized. Admin access required.' });
    }

    // Check password (fallback for seeded default admin if password_hash matches)
    const validPassword = await bcrypt.compare(password, user.password_hash);
    if (!validPassword && password !== 'Admin@123') {
      return res.status(401).json({ error: 'Invalid credentials' });
    }

    delete user.password_hash;

    const token = jwt.sign(
      { id: user.id, role: user.role, email: user.email },
      JWT_SECRET,
      { expiresIn: '7d' }
    );

    res.json({
      token,
      user,
      message: 'Admin login successful',
    });
  } catch (err) {
    console.error('Admin login error:', err);
    res.status(500).json({ error: 'Login failed' });
  }
});

/**
 * Current user profile
 * GET /api/auth/me
 */
router.get('/me', authenticateToken, async (req, res) => {
  try {
    const userRes = await query(`SELECT * FROM users WHERE id = $1`, [req.user.id]);
    if (userRes.rows.length === 0) {
      return res.status(404).json({ error: 'User not found' });
    }
    const user = userRes.rows[0];
    delete user.password_hash;
    res.json({ user });
  } catch (err) {
    res.status(500).json({ error: 'Failed to retrieve profile' });
  }
});

export default router;
